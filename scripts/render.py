# ------------------------------------------------------------------ build


def build() -> dict[Path, str]:
    tools_doc = load("tools.json")
    data = {
        "tools": tools_doc["tools"],
        "research": load("research.json")["references"],
        "paradigms": load("paradigms.json")["paradigms"],
        "training": load("training.json")["resources"],
        "collections": load("collections.json")["collections"],
    }
    out: dict[Path, str] = {}

    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    blocks = {
        "badges": render_badges(data["tools"], tools_doc["version"], tools_doc["last_reviewed"]),
        "stats": render_stats(data),
        "tools": render_tools(data["tools"]),
        "research": render_research(data["research"]),
        "learning": render_learning(data["collections"], data["training"]),
        "docs": render_docs_table("docs/"),
    }
    for name, content in blocks.items():
        readme = fill(readme, name, content, "README.md")
    out[readme_path] = readme

    minutes: dict[str, int] = {}
    for index, (file, title, _, track) in enumerate(DOCS):
        path = DOCS_DIR / file
        text = ensure_doc_markers(path.read_text(encoding="utf-8"))
        minutes[file] = reading_minutes(text)
        text = fill(text, "doc-header", doc_header(index, minutes[file]), file)
        text = fill(text, "doc-footer", doc_footer(index), file)
        out[path] = text
        _, name, _, colour, _ = TRACK[track]
        out[STRIPS / f"{file.removesuffix('.md')}.svg"] = strip_svg(index, f"OSINTAI docs  ›  {name}", title, colour)

    out[STRIPS / "index.svg"] = strip_svg(None, f"OSINTAI docs  ›  {len(TRACKS)} tracks", "Reading order", "#5EEAD4")
    out[DOCS_DIR / "README.md"] = docs_hub(minutes)
    out[SCHEMAS / "README.md"] = schemas_readme()
    out[CATALOG / "README.md"] = catalog_readme()
    out[ROOT / "site" / "groups.json"] = json.dumps(
        [{"title": title.split(" ", 1)[1], "emoji": title.split(" ", 1)[0], "blurb": blurb, "ids": ids}
         for title, blurb, ids in GROUPS], ensure_ascii=False, indent=2) + "\n"
    return out


def main() -> int:
    stale = []
    for path, content in build().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if "--check" not in sys.argv:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if "--check" in sys.argv:
        if stale:
            print("Out of date: " + ", ".join(map(str, stale)))
            print("Run: python scripts/render.py")
            return 1
        print("Generated files are in sync with their sources.")
        return 0
    print("Updated: " + (", ".join(map(str, stale)) if stale else "nothing, already in sync"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
