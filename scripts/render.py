"""Render every generated part of the OSINTAI repository from its sources.

Stdlib only. Sources of truth:
  - catalog/*.json  -> README badges, stats, tool catalog, research, learning
  - schemas/*.json  -> schemas/README.md
  - DOCS / TRACKS   -> docs/README.md, README docs table, per-doc header,
                       footer navigation and assets/docs/*.svg strips
  - GROUPS          -> README catalog grouping and site/groups.json

Blocks between `<!-- osintai:NAME:start -->` and `<!-- osintai:NAME:end -->`
are generated; files marked "generated" are owned entirely by this script.

    python scripts/render.py          # rewrite everything that changed
    python scripts/render.py --check  # exit 1 if anything is stale (used in CI)
"""

