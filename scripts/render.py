# ------------------------------------------------------------------ helpers


def load(name: str) -> dict:
    with (CATALOG / name).open(encoding="utf-8") as handle:
        return json.load(handle)


def badge(label: str, message: str, color: str) -> str:
    def esc(text: str) -> str:
        return quote(text.replace("-", "--").replace("_", "__"), safe="")
    return f"https://img.shields.io/badge/{esc(label)}-{esc(message)}-{color}?style=flat-square"


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def tags(values: list[str], limit: int = 3) -> str:
    return " ".join(f"`{v}`" for v in values[:limit])


def block_re(name: str) -> re.Pattern:
    return re.compile(rf"(<!-- osintai:{name}:start -->\n)(?:.*?\n)?(<!-- osintai:{name}:end -->)", re.S)


def fill(text: str, name: str, content: str, where: str) -> str:
    pattern = block_re(name)
    if not pattern.search(text):
        raise SystemExit(f"{where} is missing the osintai:{name} markers")
    return pattern.sub(lambda m: m.group(1) + content + "\n" + m.group(2), text)


def strip_blocks(text: str) -> str:
    return re.sub(r"<!-- osintai:[\w-]+:start -->.*?<!-- osintai:[\w-]+:end -->", "", text, flags=re.S)


def reading_minutes(text: str) -> int:
    words = len(re.findall(r"[A-Za-z0-9À-ÿ]+", strip_blocks(text)))
    return max(1, round(words / 220))


