def strip_svg(current: int | None, kicker: str, title: str, colour: str) -> str:
    """A 1280x96 header strip: kicker and title left, reading-order dots right."""
    dots = []
    spans: dict[str, list[int]] = {}
    x = 700
    for index, (_, _, _, track) in enumerate(DOCS):
        if index and DOCS[index - 1][3] != track:
            x += 14
        spans.setdefault(track, []).append(x)
        c = TRACK[track][3]
        if current is not None and index == current:
            dots.append(f'<circle cx="{x}" cy="44" r="11" fill="none" stroke="{c}" stroke-width="2" opacity="0.6"/>'
                        f'<circle cx="{x}" cy="44" r="6.5" fill="{c}"/>')
        elif current is not None and index < current:
            dots.append(f'<circle cx="{x}" cy="44" r="5" fill="{c}" opacity="0.75"/>')
        else:
            dots.append(f'<circle cx="{x}" cy="44" r="5" fill="none" stroke="{c}" stroke-width="2" opacity="0.8"/>')
        x += 30
    for track, xs in spans.items():
        dots.append(f'<text x="{(xs[0] + xs[-1]) / 2:g}" y="80" text-anchor="middle" fill="#64748B" '
                    f'font-family="Segoe UI, Inter, Helvetica Neue, Arial, sans-serif" font-size="12">'
                    f'{escape(TRACK[track][1])}</text>')
    counter = (f"{current + 1:02d} / {len(DOCS)}" if current is not None else f"{len(DOCS)} documents")
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 96" width="1280" height="96" role="img" aria-label="{escape(kicker)}: {escape(title)}">
  <rect width="1280" height="96" rx="14" fill="#0B1222"/>
  <rect x="0" y="0" width="8" height="96" rx="4" fill="{colour}"/>
  <g font-family="Segoe UI, Inter, Helvetica Neue, Arial, sans-serif">
    <text x="40" y="38" fill="#94A3B8" font-size="16" font-weight="600">{escape(kicker)}</text>
    <text x="40" y="72" fill="{colour}" font-size="28" font-weight="700">{escape(title)}</text>
  </g>
  {''.join(dots)}
  <text x="1244" y="50" text-anchor="end" fill="#94A3B8" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="15">{counter}</text>
</svg>
"""


def doc_header(index: int, minutes: int) -> str:
    file, title, _, track = DOCS[index]
    _, name, emoji, _, _ = TRACK[track]
    slug = file.removesuffix(".md")
    return (f'<a href="README.md"><img src="../assets/docs/{slug}.svg" '
            f'alt="OSINTAI docs — {name} track, document {index + 1} of {len(DOCS)}" width="100%"></a>\n\n'
            f"[OSINTAI](../README.md) › [Docs](README.md) › {emoji} **{name}** "
            f"&nbsp;·&nbsp; <sub>about {minutes} min read</sub>")


def doc_footer(index: int) -> str:
    prev_link = ("[OSINTAI README](../README.md)" if index == 0
                 else f"[{DOCS[index - 1][1]}]({DOCS[index - 1][0]})")
    next_link = ("[Back to the README](../README.md)" if index == len(DOCS) - 1
                 else f"[{DOCS[index + 1][1]}]({DOCS[index + 1][0]})")
    return ("---\n\n"
            "| ← Previous | | Next → |\n"
            "|:---|:---:|---:|\n"
            f"| {prev_link} | [📚 All docs](README.md) | {next_link} |")


def ensure_doc_markers(text: str) -> str:
    if "<!-- osintai:doc-header:start -->" not in text:
        text = "<!-- osintai:doc-header:start -->\n<!-- osintai:doc-header:end -->\n\n" + text
    if "<!-- osintai:doc-footer:start -->" not in text:
        text = text.rstrip("\n") + "\n\n<!-- osintai:doc-footer:start -->\n<!-- osintai:doc-footer:end -->\n"
    return text


def docs_hub(minutes: dict[str, int]) -> str:
    total = sum(minutes.values())
    out = [GENERATED_NOTE, "",
           '<a href="../README.md"><img src="../assets/docs/index.svg" '
           f'alt="OSINTAI docs — {len(DOCS)} documents in {len(TRACKS)} tracks" width="100%"></a>', "",
           "[OSINTAI](../README.md) › **Docs**", "",
           "# OSINTAI docs", "",
           f"{len(DOCS)} guides in {len(TRACKS)} tracks, about {total} minutes end to end. "
           "Read the tracks in order the first time; after that, jump straight to what you need.", ""]
    number = 0
    for track_id, name, emoji, _, purpose in TRACKS:
        out += [f"## {emoji} {name}", "", purpose, "",
                "| # | Document | Read it when you want to… | Time |", "|:---:|---|---|---:|"]
        for file, title, why, track in DOCS:
            if track != track_id:
                continue
            number += 1
            out.append(f"| {number} | **[{title}]({file})** | {why} | {minutes[file]} min |")
        out.append("")
    out += ["---", "",
            "Machine-readable data lives in [`catalog/`](../catalog/README.md) "
            "and is described by [`schemas/`](../schemas/README.md).", ""]
    return "\n".join(out)


