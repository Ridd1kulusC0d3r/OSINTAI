def schema_rules(spec: dict) -> str:
    rules = []
    if "enum" in spec:
        rules.append("one of " + ", ".join(f"`{v}`" for v in spec["enum"]))
    if "pattern" in spec:
        rules.append(f"matches `{spec['pattern']}`")
    if "format" in spec:
        rules.append(f"{spec['format']} format")
    if spec.get("minLength"):
        rules.append("not empty")
    if spec.get("minItems"):
        rules.append(f"at least {spec['minItems']} item" + ("s" if spec["minItems"] > 1 else ""))
    items = spec.get("items", {})
    if "enum" in items:
        rules.append("items from " + ", ".join(f"`{v}`" for v in items["enum"]))
    return "; ".join(rules) or "—"


def schema_type(spec: dict) -> str:
    if "enum" in spec and "type" not in spec:
        return "enum"
    kind = spec.get("type", "any")
    if kind == "array":
        return f"list of {spec.get('items', {}).get('type', 'any')}"
    return kind if isinstance(kind, str) else " / ".join(kind)


def schemas_readme() -> str:
    out = [GENERATED_NOTE, "",
           "[OSINTAI](../README.md) › **Schemas**", "",
           "# Catalog schemas", "",
           "JSON Schemas (draft 2020-12) for each record type in [`catalog/`](../catalog/README.md). "
           "They document the contract; [`scripts/validate_catalog.py`](../scripts/validate_catalog.py) "
           "enforces it in CI without external dependencies.", ""]
    for path in sorted(SCHEMAS.glob("*.schema.json")):
        schema = json.loads(path.read_text(encoding="utf-8"))
        required = set(schema.get("required", []))
        out += [f"## {schema.get('title', path.stem)}", "",
                f"File: [`{path.name}`]({path.name})", "",
                "| Field | Type | Required | Rules |", "|---|---|:---:|---|"]
        for field, spec in schema.get("properties", {}).items():
            out.append(f"| `{field}` | {schema_type(spec)} | {'✔' if field in required else ''} "
                       f"| {cell(schema_rules(spec))} |")
        if schema.get("additionalProperties") is False:
            out += ["", "<sub>No fields beyond these are allowed.</sub>"]
        out.append("")
    return "\n".join(out)


